"""Lesson probe `us-frozen-port`: measure, offline, what porting the arm-sim watchdog's frozen-echo check
into the pod's triage would catch and what it would cost in false alarms.

The port: `check_ultrasonic_frozen` (prototypes/arm-sim/armsim/level1.py:30-44, "the rule Olir's
`check_ultrasonic` is missing") run beside today's `firmware/healer/healer/detect.py` rules.
"Before" = detect.py alone; "after" = detect.py plus the port. A window counts as caught or as a
false alarm when it raises any warn/critical finding (`workerbench.l1.ALARM`).

Inputs (design.md §6):
  1. the gen_pod test items (seed 99, 30 per variant = 600, incl. five hard-negative families),
     regenerated by the committed generator;
  2. 120 frozen windows of >= 4 s, committed at cloud/tests/fixtures/review/us_frozen_windows.json
     (rebuild with --regen-windows; the healthy accel/health context is regenerated per window);
  3. Olir's real recording firmware/ultrasonic-sample.json, as sliding 4 s windows (false alarms only).

Standard library only; runs on the host:
    python3 cloud/scripts/lesson_probe.py [--out PATH] [--fixture-out PATH]
Writes data/learning/probes/us-frozen-port.json (data/ is gitignored). Every number is computed here.
"""
import argparse
import collections
import datetime
import json
import random
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "prototypes" / "arm-sim"))
from workerbench import gen_pod, l1  # noqa: E402  (l1 puts firmware/healer on sys.path itself)

PROBE, KIND = "us-frozen-port", "us_frozen"
PORT = {"from": "prototypes/arm-sim/armsim/level1.py:30-44 (check_ultrasonic_frozen)",
        "to": ["firmware/healer/healer/detect.py", "arm/safe_replay.py"]}
WINDOWS = REPO / "cloud" / "tests" / "fixtures" / "review" / "us_frozen_windows.json"
SAMPLE = REPO / "firmware" / "ultrasonic-sample.json"
OUT = REPO / "data" / "learning" / "probes" / f"{PROBE}.json"
WINDOW_SEED, TEST_SEED, PER_VARIANT, D_HZ = 7, 99, 30, 10


def judge(snap):
    """(detect alarms?, detect-or-port alarms?) on one podd-style snapshot."""
    s = {"now": snap["now"], "D": snap.get("D") or [], "A": snap.get("A") or [], "H": snap.get("H") or [],
         "E": snap.get("E") or [], "link": snap.get("link") or {"state": "up"}}
    base = any(f["severity"] in l1.ALARM for f in l1.detect.run(s))
    port = any(f["severity"] in l1.ALARM for f in l1.level1.check_ultrasonic_frozen({"now": s["now"], "D": s["D"]}))
    return base, base or port


def regen_windows():
    """120 frozen windows: healthy rows 1..20 (x6), then the last row repeated, so >= 40 rows (4 s) frozen."""
    rng, out = random.Random(WINDOW_SEED), []
    for healthy_n in range(1, 21):
        for k in range(6):
            now = round(1794100000.0 + rng.uniform(0, 86400), 3)
            target = rng.uniform(600, 2000)
            p, D, _, _, fr = gen_pod._frozen(rng, now, target, healthy_n, None)
            out.append({"id": f"frozen-{healthy_n:02d}-{k}", "now": now, "boot_ts": round(p.boot_ts, 4),
                        "target_mm": round(target, 1), "healthy_rows": healthy_n, "frozen_rows": len(fr),
                        "frozen_s": round(len(fr) / D_HZ, 1), "D": D})
    doc = {"what": "120 simulated ultrasonic freezes of >= 4 s (D rows only, 10 Hz), for lesson_probe.py",
           "generator": f"workerbench.gen_pod._frozen with random.Random({WINDOW_SEED}), healthy rows 1..20 x 6, "
                        "target 600-2000 mm; accel/health/boot context is regenerated healthy by the probe",
           "command": "python3 cloud/scripts/lesson_probe.py --regen-windows", "windows": out}
    WINDOWS.parent.mkdir(parents=True, exist_ok=True)
    WINDOWS.write_text(json.dumps(doc, separators=(",", ":")) + "\n")
    return doc


def window_snapshot(i, w):
    """The committed D rows plus a healthy pod's accel/health/boot context (same boot time)."""
    p = gen_pod.Pod(random.Random(f"ctx-{i}"), w["now"], boot_age=w["now"] - w["boot_ts"])
    _, A, H = p.healthy(w["target_mm"])
    return p.snap(w["D"], A, H)


def score(snaps):
    n = len(snaps)
    b = a = 0
    for s in snaps:
        x, y = judge(s)
        b, a = b + x, a + y
    return n, b, a


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--fixture-out", help="also write a copy here (e.g. cloud/tests/fixtures/review/probe_us_frozen.json)")
    ap.add_argument("--regen-windows", action="store_true", help="rebuild the committed 120-window set first")
    a = ap.parse_args()
    t0 = time.time()

    wdoc = regen_windows() if a.regen_windows else json.loads(WINDOWS.read_text())
    wins = wdoc["windows"]
    n_fr, fr_b, fr_a = score([window_snapshot(i, w) for i, w in enumerate(wins)])

    items, _bad = gen_pod.make_items(TEST_SEED, "test", PER_VARIANT)
    by = collections.defaultdict(lambda: [0, 0, 0])       # variant -> [n, before, after]
    healthy = [0, 0, 0]
    other_faults = [0, 0, 0]                              # non-frozen faults where only the port fired
    hard = set()
    for it in items:
        x, y = judge(it["snapshot"])
        v, lab = it["meta"]["variant"], it["label"]
        r = by[v]
        r[0], r[1], r[2] = r[0] + 1, r[1] + x, r[2] + y
        if lab["status"] == "healthy":
            healthy[0], healthy[1], healthy[2] = healthy[0] + 1, healthy[1] + x, healthy[2] + y
            if lab.get("hard_negative"):
                hard.add(v)
        elif lab["kind"] != KIND:
            other_faults[0] += 1
            other_faults[1] += (y and not x)

    rows = json.loads(SAMPLE.read_text())["rows"]
    rows = sorted((r for r in rows if r.get("type", "D") == "D"), key=lambda r: r["ts"])
    real = []
    for i, r in enumerate(rows):
        if r["ts"] - rows[0]["ts"] < 4.0:                   # need a full 4 s of history (the port's window)
            continue
        real.append({"now": r["ts"], "D": rows[:i + 1], "A": [], "H": [], "E": [], "link": {"state": "up"}})
    n_real, real_b, real_a = score(real)

    fe, fo = by["frozen-early"], by["frozen-at-out_of_range"]
    fe_s = next(it["label"]["facts"]["n_identical"] for it in items if it["meta"]["variant"] == "frozen-early") / D_HZ
    shortest = min(w["frozen_s"] for w in wins)
    limits = [
        f"a {fe_s:.1f} s freeze (gen_pod 'frozen-early') is caught {fe[2]} of {fe[0]} times with the port "
        f"({fe[1]} of {fe[0]} today): the check needs the whole 4 s window frozen",
        f"a freeze on out-of-range rows (the jaw in the beam at home) is caught {fo[2]} of {fo[0]} times: "
        "the check reads only st=ok rows",
        f"every freeze here is simulated (gen_pod, >= {shortest:.1f} s); the real recording "
        f"({len(rows)} rows, {rows[-1]['ts'] - rows[0]['ts']:.0f} s) checks false alarms only",
    ]
    doc = {
        "probe": PROBE, "kind": KIND,
        "description": "Port the arm-sim watchdog's frozen-echo check (zero echo-time jitter over 4 s of ok "
                       "rows) into the pod's detect.py and the arm's start gate",
        "port": PORT,
        "before": {"caught": fr_b, "of": n_fr, "false_alarms": healthy[1] + real_b, "healthy": healthy[0] + n_real},
        "after": {"caught": fr_a, "of": n_fr, "false_alarms": healthy[2] + real_a, "healthy": healthy[0] + n_real},
        "sets": {
            "frozen_windows": {"source": str(WINDOWS.relative_to(REPO)), "n": n_fr, "before": fr_b, "after": fr_a,
                               "frozen_s_min": shortest},
            "gen_pod_test": {"seed": TEST_SEED, "items": len(items), "healthy": healthy[0],
                             "false_alarms_before": healthy[1], "false_alarms_after": healthy[2],
                             "hard_negative_families": sorted(hard),
                             "port_only_alarms_on_other_faults": other_faults[1], "other_faults": other_faults[0],
                             "by_variant": {v: {"n": r[0], "before": r[1], "after": r[2]} for v, r in sorted(by.items())}},
            "real_sample": {"source": str(SAMPLE.relative_to(REPO)), "windows": n_real,
                            "false_alarms_before": real_b, "false_alarms_after": real_a},
        },
        "definitions": "caught / false alarm = any warn or critical finding in the window; before = detect.py "
                       "RULES, after = detect.py RULES + check_ultrasonic_frozen",
        "limits": limits,
        "command": "python3 cloud/scripts/lesson_probe.py" + (" --regen-windows" if a.regen_windows else ""),
        "rev": _rev(),
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "seconds": round(time.time() - t0, 2),
    }
    text = json.dumps(doc, indent=2) + "\n"
    for path in filter(None, [a.out, a.fixture_out]):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(text)
        print(f"wrote {path}")
    b, af = doc["before"], doc["after"]
    print(f"{PROBE}: caught {b['caught']}/{b['of']} -> {af['caught']}/{af['of']}; false alarms "
          f"{b['false_alarms']} -> {af['false_alarms']} of {af['healthy']} healthy windows "
          f"({healthy[0]} gen_pod + {n_real} real); {doc['seconds']} s")
    for s in limits:
        print("  limit:", s)
    return 0


def _rev():
    try:
        return subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"], capture_output=True,
                              text=True, timeout=5).stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        return None


if __name__ == "__main__":
    sys.exit(main())
