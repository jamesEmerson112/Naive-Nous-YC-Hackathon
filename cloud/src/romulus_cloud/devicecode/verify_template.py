"""Held-out verify for the device code, generated from bench/tasks.py's hidden checks (B1).

Generated by `python -m romulus_cloud.devicecode.verify_from_bench` (`make device-verify`);
don't edit it, regenerate it. The replay copies it to verify/ next to bench_reference.json
and runs it with the image's fixed verify command (no conftest, clean config), so the code
under test never sees or configures it.

For every scenario a software benchmark task uses (its incident scenario plus the normal and
hand_close regressions), the app must finish with no incident and send exactly the arm
commands the canonical app sent, on a fresh copy of the sim. sim/ and supervisor/ must be
byte-identical to the canonical ones (the bench fails a healer that edits sim/).
"""

import hashlib
import json
import shutil
import sys
from pathlib import Path

import pytest

WORK = Path(__file__).resolve().parents[1]
REF = json.loads(Path(__file__).with_name("bench_reference.json").read_text())
SIM_RUNTIME = ("arm_commands.jsonl", "arm_state.json", "arm_faults.json", "__pycache__")
sys.path.insert(0, str(WORK / "supervisor"))
import monitor  # noqa: E402


def _hashes():
    out = {}
    for top in ("sim", "supervisor"):
        for p in sorted((WORK / top).rglob("*")):
            if p.is_file() and "__pycache__" not in p.parts and p.name not in SIM_RUNTIME:
                out[p.relative_to(WORK).as_posix()] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


def _same(a, b, tol=1e-6):
    return len(a) == len(b) and all(
        x.keys() == y.keys() and all(abs(float(x[k]) - float(y[k])) <= tol for k in x)
        for x, y in zip(a, b, strict=True)
    )


def test_sim_and_supervisor_are_canonical():
    assert _hashes() == REF["hashes"], "sim/ or supervisor/ differs from the canonical code"


@pytest.mark.parametrize("name", sorted(REF["scenarios"]))
def test_same_arm_commands_as_canonical(name, tmp_path):
    case = REF["scenarios"][name]
    robot, sim = tmp_path / "robot", tmp_path / "sim"
    skip = shutil.ignore_patterns("logs", "run", "__pycache__")
    shutil.copytree(WORK / "robot", robot, ignore=skip)
    shutil.copytree(WORK / "sim", sim, ignore=shutil.ignore_patterns(*SIM_RUNTIME))
    result = monitor.run_app(robot, sim, case["scenario"])
    incident = monitor.classify(result)
    where = f"{name} ({', '.join(case['tasks'])})"
    tail = "\n".join(result["log_tail"][-15:])
    assert incident is None, f"{where}: {incident and incident['detail']}\n{tail}"
    commands = monitor._jsonl(sim / "arm_commands.jsonl")
    assert _same(commands, case["commands"]), (
        f"{where}: {len(commands)} arm commands differ from the "
        f"canonical app's {len(case['commands'])}"
    )
