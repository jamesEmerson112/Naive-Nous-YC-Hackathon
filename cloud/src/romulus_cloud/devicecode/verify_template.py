"""Held-out verify for the device code, from bench/tasks.py's planted faults (B1).

Generated by `python -m romulus_cloud.devicecode.verify_from_bench` (`make device-verify`);
don't edit it, regenerate it. The replay copies it to verify/ with `bench_reference.json`,
`bench_monitor.py` and `bench_sim/`, and runs it with the image's fixed verify command (no
conftest, clean config).

**It trusts nothing in the candidate tree but the app under test** (`robot/`). The
supervisor (`bench_monitor.py`) and the fake hardware (`bench_sim/`) are frozen copies of
the code version this was generated from, held out with this file, so a patch to
`supervisor/` or `sim/` can't change how the check runs or what it sees.

Each scenario a software bench task uses (its incident scenario plus the normal and
hand_close regressions) must keep SPEC.md's properties, in the style of device/tests: the
run finishes every step with no incident (no crash, no hang, gripper never opened while
holding: rules 1, 4, 5), and each step's arm command fits that step's reading (rules 2, 3).
Properties, not exact arm commands: a legitimate fix passes. The thresholds are frozen from
the generating version's config.toml. One extra check, labelled as policy: the candidate
leaves sim/ and supervisor/ byte-identical, as the bench requires of a healer.
"""

import hashlib
import importlib.util
import json
import shutil
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
WORK = HERE.parent  # the candidate tree; only robot/ is used from it
REF = json.loads((HERE / "bench_reference.json").read_text())
SPEC = REF["spec"]
SIM_RUNTIME = ("arm_commands.jsonl", "arm_state.json", "arm_faults.json", "__pycache__")


def _load_monitor():
    spec = importlib.util.spec_from_file_location("bench_monitor", HERE / "bench_monitor.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


monitor = _load_monitor()


def _readings(scenario, steps):
    """What the canonical fake sensor returns at each step (TraceSensor's rules)."""
    lines = (HERE / "bench_sim" / "traces" / scenario["trace"]).read_text().splitlines()
    values = [ln.strip() for ln in lines if ln.strip() and not ln.strip().startswith("#")]
    values = [None if v.lower() == "none" else float(v) for v in values]
    hold = scenario.get("trace_end", "loop") == "hold"
    return [values[i] if i < len(values) else values[-1 if hold else i % len(values)]
            for i in range(steps)]  # fmt: skip


def _valid(d):
    return d is not None and SPEC["min_cm"] <= d <= SPEC["max_cm"]


def _hashes():
    out = {}
    for top in ("sim", "supervisor"):
        for p in sorted((WORK / top).rglob("*")):
            if p.is_file() and "__pycache__" not in p.parts and p.name not in SIM_RUNTIME:
                out[p.relative_to(WORK).as_posix()] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


def test_policy_sim_and_supervisor_untouched():
    """Policy, not behaviour: the bench fails a healer that edits sim/ or supervisor/."""
    assert _hashes() == REF["hashes"], "sim/ or supervisor/ differs from the canonical code"


@pytest.mark.parametrize("name", sorted(REF["scenarios"]))
def test_spec_properties_hold(name, tmp_path):
    case = REF["scenarios"][name]
    scenario, where = case["scenario"], f"{name} ({', '.join(case['tasks'])})"
    robot, sim = tmp_path / "robot", tmp_path / "sim"
    skip = shutil.ignore_patterns("logs", "run", "__pycache__")
    shutil.copytree(WORK / "robot", robot, ignore=skip)
    shutil.copytree(HERE / "bench_sim", sim, ignore=shutil.ignore_patterns(*SIM_RUNTIME))
    result = monitor.run_app(robot, sim, scenario)
    incident = monitor.classify(result)
    tail = "\n".join(result["log_tail"][-15:])
    assert incident is None, f"{where}: {incident and incident['detail']}\n{tail}"
    commands = monitor._jsonl(sim / "arm_commands.jsonl")
    assert len(commands) == scenario["steps"], f"{where}: {len(commands)} commands"
    seen_valid = False
    for i, (command, d) in enumerate(
        zip(commands, _readings(scenario, len(commands)), strict=True)
    ):
        lift = command["shoulder_lift.pos"] - SPEC["hold_lift"]
        at = f"{where}: step {i}, reading {d}, lift {lift:.1f}"
        assert command["gripper.pos"] <= SPEC["gripper_max"], f"gripper opened ({at})"
        if _valid(d):
            seen_valid = True
            if d <= SPEC["near_cm"]:
                assert lift >= SPEC["lifted"], f"something is near but the arm didn't lift ({at})"
            elif d >= SPEC["far_cm"]:
                assert abs(lift) <= SPEC["pose_tol"], f"clear, but not in the hold pose ({at})"
        elif not seen_valid:
            assert abs(lift) <= SPEC["pose_tol"], f"no valid reading yet: should be clear ({at})"
        else:
            prev = commands[i - 1]
            same = all(abs(command[k] - prev[k]) <= 1e-6 for k in command)
            assert same, f"an invalid reading changed the arm command ({at})"
